const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const path = require('path');
const modelPath = path.resolve('docs/news-pin-model.js');
const model = fs.existsSync(modelPath) ? require(modelPath) : undefined;
const source = fs.readFileSync('docs/dashboard-controls.js','utf8');
const match = source.match(/window\.globe3dPins = ([\s\S]*?);\n  window\.globe3dView/);
assert(match, 'execute actual production pin builder');
const context = vm.createContext({Number,Math,Date,String,Object,Map,JSON,density:'sparse',newsMatches:()=>true,MagenNewsPins:model});
const build = vm.runInContext('('+match[1]+')', context);
const first = {lat:31.77,lon:35.23,text:'First fixture article',src:'Fixture A',ts:20,side:'israel',loc:'Jerusalem',link:'https://example.com/first'};
const second = {...first,text:'Second fixture article',src:'Fixture B',ts:10,link:'https://example.com/second'};
const pins = build([first,second],30);
assert(pins.every(p=>typeof p.clientId==='string' && p.clientId.length<=128),'each displayed news pin must retain an opaque reverse-selection identity');
assert.equal(pins.length,1,'coincident stories share one clickable pin rather than hiding each other');
assert.equal(pins[0].clientId,'magen-news:31.77:35.23');
assert.equal(build([{...first,lat:0,lon:0}],30).length,1,'zero coordinates are valid');
assert.equal(model.groupEvents([first,second])[0].events.length,2,'pin group retains both complete articles');
assert.equal(model.validNewsLink('javascript:alert(1)'),null,'reject executable source links');
assert.equal(model.validNewsLink('data:text/html,test'),null,'reject embedded-document source links');
assert.equal(model.validNewsLink(first.link),first.link);
assert.equal(model.groupEvents([{...first,lat:100}]).length,0,'reject impossible coordinates');
assert.equal(model.groupEvents([first,{...first}])[0].events.length,1,'duplicate feed rows do not duplicate bubble pages');
assert.equal(model.groupEvents([first,second])[0].events[0].text,first.text,'newest story first');
console.log('✓ production pins carry identity; coincident stories preserved; links safe; zero coordinates supported');
